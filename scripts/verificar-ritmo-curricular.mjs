import assert from "node:assert/strict";
import {readFileSync,readdirSync} from "node:fs";
import {createRequire} from "node:module";
const api=createRequire(import.meta.url)("../assets/curriculum-study.js");
const read=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const config=read("dados/concursos.json"),matrix=read("dados/cobertura-ima.json"),lessons=config.adaptive_study.lessons;
const sources=readdirSync(new URL("../dados/aulas-diarias/",import.meta.url)).filter(n=>n.endsWith(".json")).map(n=>read("dados/aulas-diarias/"+n));
const model=api.build(matrix,lessons,sources);
assert.equal(api.stats(model,{}).done,0);
const first=model.byLesson.get("ima-2026-11-24");
assert.equal(first.reduce((n,u)=>n+u.minutes,0),95);
assert.equal(api.stats(model,{[api.key(first[0].id)]:true}).done,first[0].minutes);
assert.equal(api.stats(model,{"ima:ima-2026-11-24:1":true}).done,55);
assert.equal(api.stats(model,{"ima:ima-2026-11-24:1":true,[api.key(first[0].id)]:false}).done,35);
assert.equal(api.stats(model,{"casan:ima-2026-11-24:1":true}).done,0);
assert.equal(api.stats(model,Object.fromEntries(first.map(u=>[api.key(u.id),true]))).done,95);
assert.ok(model.total>api.stats(model,{}).allocated);
const dup=structuredClone(sources),s=dup.find(x=>x.id==="ima-2026-11-24");s.modules[0].sections[1].curriculum={...s.modules[0].sections[0].curriculum};
assert.equal(api.build(matrix,lessons,dup).units.size,model.units.size-1);
s.modules[0].sections[1].curriculum.minutes++;
assert.throws(()=>api.build(matrix,lessons,dup),/divergente/);
const over=structuredClone(sources);over.find(x=>x.id==="ima-2026-11-24").modules[0].sections[0].curriculum.minutes=1000;
assert.throws(()=>api.build(matrix,lessons,over),/excede/);
console.log("Ritmo por esforço: "+model.units.size+" unidades únicas, "+model.total+" minutos reservados; testes aprovados.");
